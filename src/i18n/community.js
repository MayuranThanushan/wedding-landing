export function errText(s, e) {
  const m = e?.message;
  if (m === 'name') return s.errName;
  if (m === 'limit') return s.errLimit;
  if (m === 'invalid') return s.errInvalid;
  return s.errGeneric;
}

/** "3 days ago" in the guest's language. */
export function relTime(iso, locale, s) {
  const diff = (new Date(iso).getTime() - Date.now()) / 1000;
  if (Math.abs(diff) < 60) return s.justNow;
  const units = [['year', 31536000], ['month', 2592000], ['week', 604800], ['day', 86400], ['hour', 3600], ['minute', 60]];
  try {
    const rtf = new Intl.RelativeTimeFormat(locale, { numeric: 'auto' });
    for (const [u, sec] of units) if (Math.abs(diff) >= sec) return rtf.format(Math.round(diff / sec), u);
  } catch { /* old browser */ }
  return new Date(iso).toLocaleDateString();
}
